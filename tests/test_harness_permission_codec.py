def test_permission_records_are_immutable_and_freeze_tokens() -> None:
    tokens = ["git", "push"]
    rule = PermissionCommandRule(tokens, "allow", "Bash(git push:*)")
    tokens.append("--force")
    assert rule.tokens == ("git", "push")
    with pytest.raises(TypeError):
        rule.tokens[0] = "rm"  # type: ignore[index]

    observation = NativePermissionRuleObservation(["git"], "allow", True)
    assert observation.tokens == ("git",)
    with pytest.raises(TypeError):
        observation.tokens[0] = "rm"  # type: ignore[index]


def test_codex_render_is_byte_exact() -> None:
    codec = CodexPermissionCodec()
    rule = PermissionCommandRule(("git", "push"), "ask", "Bash(git push:*)")
    assert codec.encode((rule,)) == (
        "# Generated by Skill Hub — do not edit; managed via the hub registry.\n"
        "\n"
        'prefix_rule(pattern = ["git", "push"], decision = "prompt", '
        'justification = "skill-hub: ask Bash(git push:*)")\n'
    )


def test_codex_decode_reports_literal_refusals_and_source_spans() -> None:
    codec = CodexPermissionCodec()
    text = (
        'prefix_rule(pattern = ["npm"], decision = "allow")\n'
        "prefix_rule(\n"
        '    pattern = ["git", "push"], decision = "prompt",\n'
        ")\n"
        'prefix_rule(pattern = [["view", "list"]], decision = "allow")\n'
        'prefix_rule(pattern = ["gh"], decision = "allow", not_match = ["--force"])\n'
        'prefix_rule(pattern = ["rm"], decision = "unknown")\n'
    )
    observations = codec.decode(text)
    assert len(observations) == 5
    assert observations[0].tokens == ("npm",)
    assert observations[0].native_decision == "allow"
    assert observations[0].importable
    assert observations[1].tokens == ("git", "push")
    assert observations[1].end_lineno > observations[1].lineno  # multiline span
    assert not observations[2].importable
    assert "union" in (observations[2].reason or "")
    assert not observations[3].importable
    assert "match" in (observations[3].reason or "")
    assert not observations[4].importable
    assert observations[4].native_decision == "unknown"


def test_permission_codec_calls_do_not_share_outputs() -> None:
    codec = OpenCodePermissionCodec()
    rule = PermissionCommandRule(("npm",), "allow", "Bash(npm:*)")
    first = codec.encode((rule,))
    second = codec.encode((rule,))
    assert first == second == {"npm *": "allow"}
    with pytest.raises(TypeError):
        first["npm *"] = "deny"  # type: ignore[index]
    assert second == {"npm *": "allow"}


def test_opencode_orders_specific_rules_last_and_duplicate_wins() -> None:
    codec = OpenCodePermissionCodec()
    rules = (
        PermissionCommandRule(("git", "push"), "deny", "Bash(git push:*)"),
        PermissionCommandRule(("git",), "allow", "Bash(git:*)"),
        PermissionCommandRule(("git",), "ask", "Bash(git:*)"),
    )
    assert list(codec.encode(rules).items()) == [
        ("git *", "ask"),
        ("git push *", "deny"),
    ]


def test_opencode_decode_refuses_catchall_and_unknown_decisions() -> None:
    codec = OpenCodePermissionCodec()
    observations = codec.decode(
        {"git push *": "deny", "*": "allow", "npm *": "maybe"}
    )
    assert observations[0].tokens == ("git", "push")
    assert observations[0].importable
    assert observations[1].tokens is None
    assert not observations[1].importable
    assert observations[2].native_decision == "maybe"
    assert not observations[2].importable


