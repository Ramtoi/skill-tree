@pytest.mark.parametrize("constraint", ["match=[]", "match=()", "not_match=[]", "match=False"])
def test_codex_empty_constraint_keeps_importable_rule_and_literal_metadata(constraint):
    """TA-1-f47f: pinned against the public `CodexPermissionCodec.decode`
    (the observation type already exposes these fields publicly), not the
    private key-renaming `_parse_prefix_rules` wrapper."""
    observed = CodexPermissionCodec().decode(
        'prefix_rule(pattern=["npm"], justification={"note": ["keep", (1, 2)]}, ' + constraint + ')'
    )[0]
    assert observed.importable is True
    assert observed.has_match is False
    # The public codec freezes nested structures (mappingproxy/tuple) so the
    # observation stays hashable-safe; the literal values still round-trip.
    assert dict(observed.justification) == {"note": ("keep", (1, 2))}
    assert isinstance(observed.justification["note"], tuple)
    assert isinstance(observed.justification["note"][1], tuple)


def test_codex_unknown_decision_retains_value_and_reason():
    """TA-1-f47f: pinned against the public codec decode; see the note above."""
    observation = CodexPermissionCodec().decode('prefix_rule(pattern=["git"], decision=123)')[0]
    assert not observation.importable
    assert observation.native_decision == 123
    assert observation.reason == "unsupported decision 123"


def test_opencode_import_preserves_native_spacing(tmp_path):
    import json

    from skill_hub.domain.permissions.permissions import ProjectScope
    from skill_hub.infrastructure.permissions.permission_adapter_opencode import OpenCodePermissionAdapter

    config = tmp_path / "opencode.json"
    config.write_text(json.dumps({"permission": {"bash": {"git  push *": "ask"}}}), encoding="utf-8")
    imported = OpenCodePermissionAdapter().discover_existing(ProjectScope("fixture", str(tmp_path)), "opencode")
    assert [rule.pattern for rule in imported.ask] == ["Bash(git  push:*)"]


def test_permission_observation_keeps_literal_metadata_immutable():
    observation = CodexPermissionCodec().decode(
        'prefix_rule(pattern=["git"], justification={"notes": ["keep"]})'
    )[0]
